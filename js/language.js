let currentLanguage = 'cs';

function detectUserLanguage() {
    const savedLang = localStorage.getItem('preferredLanguage');
    if (savedLang) {
        return savedLang;
    }

    const browserLang = navigator.language || navigator.userLanguage;
    
    if (browserLang.startsWith('cs')) {
        return 'cs';
    }
    
    return 'en';
}

function getNestedValue(obj, path) {
    return path.split('.').reduce((current, key) => current?.[key], obj);
}

function translatePage(lang) {
    currentLanguage = lang;
    
    document.documentElement.lang = lang;
    
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = getNestedValue(translations[lang], key);
        
        if (translation) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            } else {
                element.textContent = translation;
            }
        }
    });

    const listElements = document.querySelectorAll('[data-i18n-list]');
    listElements.forEach(element => {
        const key = element.getAttribute('data-i18n-list');
        const items = getNestedValue(translations[lang], key);
        
        if (items && Array.isArray(items)) {
            element.innerHTML = items.map(item => `<li>${item}</li>`).join('');
        }
    });

    const langFlag = document.getElementById('currentLang');
    if (langFlag) {
        langFlag.textContent = lang === 'cs' ? '🇨🇿' : '🇬🇧';
    }

    localStorage.setItem('preferredLanguage', lang);
}

function initLanguageToggle() {
    const langToggle = document.getElementById('langToggle');
    
    if (langToggle) {
        langToggle.addEventListener('click', () => {
            const newLang = currentLanguage === 'cs' ? 'en' : 'cs';
            translatePage(newLang);
        });
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const detectedLang = detectUserLanguage();
    translatePage(detectedLang);
    initLanguageToggle();
});
